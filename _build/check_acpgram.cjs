/* Local browser checks. Dependencies are installed in a temporary directory, not on the site. */
const fs = require('fs');
const path = require('path');
const { chromium } = require(path.join(process.env.TEMP, 'acpgram-tools/node_modules/playwright'));
(async () => {
    const output = path.join(process.env.TEMP, 'acpgram-qa');
    fs.mkdirSync(output, {recursive:true});
    const browser = await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
    const context = await browser.newContext({permissions:['clipboard-read','clipboard-write'],locale:'ru-RU'});
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const results = [];
    for (const width of [360,768,1280,1920]) {
        await page.setViewportSize({width,height:1000});
        await page.goto('http://localhost:8765/acpgram/', {waitUntil:'networkidle'});
        await page.evaluate(async () => { await Promise.all([...document.images].map(img => { img.loading='eager'; return img.decode().catch(()=>{}); })); });
        await page.evaluate(() => document.querySelectorAll('.ap-reveal-ready').forEach(el => el.classList.add('ap-visible')));
        const state = await page.evaluate(() => ({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,h1:document.querySelectorAll('h1').length,brokenImages:[...document.images].filter(i=>!i.complete||!i.naturalWidth).map(i=>i.src),iframes:document.querySelectorAll('iframe').length}));
        if (state.scrollWidth > width || state.h1 !== 1 || state.brokenImages.length || state.iframes) throw new Error(JSON.stringify(state));
        const quickLayout = await page.locator('.ap-start-steps>li').evaluateAll(items => items.map(el=>{const r=el.getBoundingClientRect();return {top:r.top,bottom:r.bottom,left:r.left};}));
        if(quickLayout.length!==4 || quickLayout.some((rect,i)=>i>0&&(rect.top<quickLayout[i-1].bottom || rect.left!==quickLayout[0].left))) throw new Error('Quick start is not sequential: '+JSON.stringify(quickLayout));
        const heroLinks = await page.locator('.ap-hero-actions a').evaluateAll(items=>items.map(a=>a.getAttribute('href')));
        if(heroLinks.slice(0,3).join(',')!=='#quick-start,#video,#installation') throw new Error('Hero shortcuts failed');
        await page.screenshot({path:path.join(output,`${width}.png`),fullPage:true});
        results.push(state);
    }
    for (const [lang,htmlLang] of [['en','en'],['ua','uk'],['ru','ru']]) {
        await page.locator('#btn-'+lang).click();
        const state = await page.evaluate(() => ({lang:document.documentElement.lang,h1:document.querySelector('h1').innerText,hiddenText:[...document.querySelectorAll('h1 > span')].filter(x=>getComputedStyle(x).display!=='none').length}));
        if (state.lang !== htmlLang || state.hiddenText !== 1) throw new Error('Language check failed: '+JSON.stringify(state));
        results.push(state);
    }
    await page.evaluate(() => { document.documentElement.style.scrollBehavior='auto'; });
    await page.locator('#video').scrollIntoViewIfNeeded();
    await page.waitForTimeout(800);
    await page.locator('#video').screenshot({path:path.join(output,'video-section.png')});
    await page.locator('#quick-start').scrollIntoViewIfNeeded();
    await page.waitForTimeout(800);
    await page.locator('#quick-start').screenshot({path:path.join(output,'install-section.png')});
    await page.route('**/assets/acpgram-stats.json', route=>route.abort());
    await page.reload({waitUntil:'networkidle'});
    const expected = JSON.parse(await page.locator('#ap-stats-fallback').textContent()).github.stars;
    const fallback = await page.locator('#hero [data-stat="github.stars"]').textContent();
    if (Number(fallback.replace(/\D/g,'')) !== expected) throw new Error('Stats fallback failed');
    await page.unroute('**/assets/acpgram-stats.json');
    results.push({statsFallback:true});
    await page.locator('#hero .ap-copy').click();
    const copied = await page.evaluate(()=>navigator.clipboard.readText());
    if (copied !== 'npm install -g acpgram') throw new Error('Wrong clipboard content');
    await page.locator('#tab-github').focus();
    await page.keyboard.press('ArrowRight');
    if (await page.locator('#tab-npm').getAttribute('aria-selected') !== 'true') throw new Error('Keyboard tabs failed');
    await page.locator('#tab-docker').click();
    if (!await page.locator('#panel-docker').isVisible() || await page.locator('#panel-github').isVisible()) throw new Error('Tab panels failed');
    await page.locator('.ap-video-facade').click();
    const iframe = page.locator('#ap-video iframe');
    if (!(await iframe.getAttribute('src')).startsWith('https://www.youtube-nocookie.com/embed/3CIc8QJZpkk')) throw new Error('Video embed failed');
    results.push({copy:copied,keyboardTabs:true,inlineVideo:await iframe.getAttribute('src')});
    await page.emulateMedia({reducedMotion:'reduce'});
    await page.reload({waitUntil:'networkidle'});
    const motion = await page.locator('.ap-chat-line').first().evaluate(el=>getComputedStyle(el).animationName);
    if (motion !== 'none') throw new Error('Reduced motion failed');
    const response = await page.goto('http://localhost:8765/acpgram');
    if (response.status() !== 200 || !page.url().endsWith('/acpgram/')) throw new Error('No-slash route failed');
    const noJs = await browser.newPage({javaScriptEnabled:false,viewport:{width:360,height:900}});
    await noJs.goto('http://localhost:8765/acpgram/');
    if (!await noJs.locator('h1').isVisible() || !await noJs.locator('#panel-docker').isVisible()) throw new Error('No-JS content failed');
    results.push({reducedMotion:true,noSlashRoute:true,noJs:true,errors});
    await page.goto(require('url').pathToFileURL(path.resolve('acpgram/index.html')).href, {waitUntil:'networkidle'});
    await page.evaluate(async () => { await Promise.all([...document.images].map(img => { img.loading='eager'; return img.decode().catch(()=>{}); })); });
    const fileState = await page.evaluate(() => ({background:getComputedStyle(document.body).backgroundColor,brokenImages:[...document.images].filter(i=>!i.complete||!i.naturalWidth).map(i=>i.src),scriptLoaded:typeof currentLang==='function',language:document.documentElement.lang}));
    if(fileState.background!=='rgb(3, 7, 18)' || fileState.brokenImages.length || !fileState.scriptLoaded) throw new Error('Direct file preview failed: '+JSON.stringify(fileState));
    results.push({filePreview:fileState});
    fs.writeFileSync(path.join(output,'results.json'), JSON.stringify(results,null,2));
    console.log(JSON.stringify({output,results},null,2));
    await browser.close();
    if(errors.length) process.exitCode=1;
})().catch(e=>{console.error(e);process.exit(1)});
